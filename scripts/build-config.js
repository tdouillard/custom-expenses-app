import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, publicConfig } from './env.js';

/* Writes config.js with the public Supabase URL and publishable key (never the DB password). */
const { url, key } = publicConfig();
const body = `// Generated by scripts/build-config.js from .env. Contains public values only.
window.APP_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseKey: key }, null, 2)};
`;
writeFileSync(join(ROOT, 'config.js'), body);
console.log('config.js written');
